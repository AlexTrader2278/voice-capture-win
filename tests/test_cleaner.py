# -*- coding: utf-8 -*-
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from cleaner import clean_fillers as c

CASES = [
    # (вход, ожидаемый выход)
    ("Ну, э-э, давай встретимся.", "Ну, давай встретимся."),
    ("Эээ, привет, как дела?", "Привет, как дела?"),
    ("Я думаю а-а-а что это хорошо", "Я думаю что это хорошо"),
    ("Это эм важный вопрос", "Это важный вопрос"),
    ("Ммм, не знаю", "Не знаю"),
    ("Мы пошли, а потом вернулись", "Мы пошли, а потом вернулись"),   # одиночное «а» живо
    ("Ну вот как бы так", "Ну вот как бы так"),                        # ну/вот/как бы живы
    ("Эта машина эмоциональна", "Эта машина эмоциональна"),             # эм внутри слова
    ("Мама мыла раму", "Мама мыла раму"),
    ("Э-э", ""),                                                        # одни паразиты -> пусто
    ("A and B", "A and B"),                                             # латинская A жива
    ("Привет, э-э-э, мир", "Привет, мир"),
    ("Хорошо. Ааа, понял.", "Хорошо. Понял."),
    ("", ""),
]

bad = 0
for src, want in CASES:
    got = c(src)
    ok = got == want
    bad += not ok
    print(("OK  " if ok else "FAIL"), repr(src), "->", repr(got), "" if ok else f"(ожидалось {want!r})")
print("\nИтого ошибок:", bad)
sys.exit(1 if bad else 0)
